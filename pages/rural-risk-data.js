// 适用范围统一取值：条件启用且条件里选了对应维度时用条件值，否则用条目自动推导值
// field: 'houseType' | 'structureType' | 'region'
function getApplicability(item, field) {
  if (!item) return '';
  const condSegs = String(item.condType || '').split('；').map(s => s.trim()).filter(Boolean);
  const condMap = { houseType: '按房屋类型启用', structureType: '按结构类型启用' };
  const segName = condMap[field];
  if (segName) {
    const seg = condSegs.find(s => s.startsWith(segName) || (field === 'structureType' && s.startsWith('按结构形式启用')));
    if (seg) {
      const vals = seg.slice(seg.indexOf('：') + 1).split('、').map(v => v.trim()).filter(Boolean);
      if (vals.length) return vals.join('、');
    }
  }
  // 地理区域的条件启用维度是乡镇，与适用范围枚举不同源，不参与条件取值
  return item[field] || '';
}

// 将 basis 中的标准编号（含 §条文号）转换为可读的《标准名称》（编号）文本
function formatBasisText(basis) {
  if (!basis) return '—';
  return basis.split('||').filter(Boolean).map(code => {
      const clauseNo = code.indexOf('§') >= 0 ? code.split('§')[1] : '';
      const stdCode = clauseNo ? code.split('§')[0] : code;
      const std = ruralStdLib.find(s => s.code === stdCode);
      const label = std ? `${std.name}（${std.code}）` : code;
      return clauseNo ? `${label} 第${clauseNo}条` : label;
  }).join('；');
}
