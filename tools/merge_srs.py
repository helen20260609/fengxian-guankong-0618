def extract_body(text):
    """去掉单篇文档的封面/版本/修订/版权/目录，仅保留正文章节"""
    lines = text.split('\n')
    start = None
    for i, ln in enumerate(lines):
        if ln.strip() == '# 1 平台功能需求':
            start = i
            break
    if start is None:
        return text.strip()
    body = lines[start:]
    # 去掉顶层 "# 1 平台功能需求" 和 "## 1.1 智能风险研判" 及引言段（整合文档已有）
    out = []
    for ln in body:
        s = ln.strip()
        if s == '# 1 平台功能需求':
            continue
        if s.startswith('## 1.1'):
            continue
        if s.startswith('智能风险研判模块作为风险管控平台的核心能力支撑'):
            continue
        out.append(ln)
    return '\n'.join(out).strip()

def renumber(body, idx, title):
    """将 '### 1.1.1 XXX' 重编号为 '## 1.1.{idx} {title}'，四级标题降为三级"""
    lines = body.split('\n')
    out = []
    for ln in lines:
        s = ln.strip()
        if s.startswith('### 1.1.1'):
            out.append(f'## 1.1.{idx} {title}')
        elif s.startswith('#### '):
            out.append('### ' + s[5:])
        else:
            out.append(ln)
    return '\n'.join(out)

